const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const source = file => import(pathToFileURL(path.resolve('examples/storm-foundry-2d/src', file)));
test('foundry contact impulses conserve momentum and dissipate energy for the configured restitution', async () => {
    const { PropPhysics } = await source('systems/PropPhysics.js');
    const { VelocityComponent, Vector2D } = await import(pathToFileURL(path.resolve('src/core/index.js')));
    const impact = [];
    const world = { settings: { current: { restitution: 0.52 } }, events: { emit: (type, event) => impact.push(event) } };
    const physics = new PropPhysics(world);
    const actor = (x, mass, vx) => ({ position: new Vector2D(x, 0), radius: 20, mass, velocity: new VelocityComponent({ vx }), size: new Vector2D(40, 40) });
    const a = actor(0, 1, 180), b = actor(37, 2, -60);
    const momentum = a.mass * a.velocity.vx + b.mass * b.velocity.vx;
    const energy = 0.5 * a.mass * a.velocity.vx ** 2 + 0.5 * b.mass * b.velocity.vx ** 2;
    physics.Resolve(a, b);
    assert(Math.abs(a.mass * a.velocity.vx + b.mass * b.velocity.vx - momentum) < 1e-9);
    assert(0.5 * a.mass * a.velocity.vx ** 2 + 0.5 * b.mass * b.velocity.vx ** 2 < energy);
    assert(a.velocity.vx < 0 && b.velocity.vx > 0);
    assert.equal(impact.length, 1);
    assert.equal(impact[0].surface, false);
});
test('foundry presets are independent live copies and invalid simulation budgets fail before allocation', async () => {
    const { FoundrySettings } = await source('data/FoundrySettings.js');
    const data = JSON.parse(fs.readFileSync('examples/storm-foundry-2d/config/showcase.json'));
    const settings = new FoundrySettings(data);
    settings.current.wind = 999;
    assert.equal(data.presets[0].wind, -85);
    settings.Apply(0);
    assert.equal(settings.current.wind, -85);
    settings.Apply(-1);
    assert.equal(settings.current.label, 'STRESS');
    assert.throws(() => new FoundrySettings({ ...data, limits: { ...data.limits, props: 100000 } }), RangeError);
    const malformed = structuredClone(data);
    malformed.presets[0].gravity = NaN;
    assert.throws(() => new FoundrySettings(malformed), RangeError);
});
