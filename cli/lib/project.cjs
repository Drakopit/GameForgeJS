const fs = require('node:fs');
const path = require('node:path');
const { slash, readJson, json, walk, applyWrites, assertNoLinks } = require('./files.cjs');
const { PACKAGE_FILE, loadPackage } = require('./package.cjs');
const { configFile } = require('./config-paths.cjs');

const ENGINE_ROOT = path.resolve(__dirname, '../..');
const PROJECT_FILE = 'gameforge.project.json';
const MODULES = Object.freeze({
    '2d': ['gameforgejs/2d', 'module2D'],
    '3d': ['gameforgejs/3d', 'module3D'],
    network: ['gameforgejs/network', 'networkModule'],
    audio: ['gameforgejs/core', 'audioModule'],
});

function validateProject(project) {
    if (!project || typeof project !== 'object' || Array.isArray(project)) throw new Error('Project manifest must be an object.');
    if (project.schemaVersion !== 1) throw new Error(`Unsupported project schemaVersion ${project.schemaVersion}; use gameforge update.`);
    if (!Array.isArray(project.modules) || project.modules.some(name => typeof name !== 'string' || !Object.hasOwn(MODULES, name))) throw new Error('Project modules must contain only official modules: 2d, 3d, network, audio.');
    if (new Set(project.modules).size !== project.modules.length) throw new Error('Project contains duplicate modules.');
    if (project.template?.startsWith('minimal-') && project.modules.includes('2d') && project.modules.includes('3d')) throw new Error('These minimal templates use one canvas: choose either 2d or 3d. Custom projects can use a separate 2D overlay.');
    for (const key of ['entry', 'runtimeConfig', 'resources']) if (typeof project[key] !== 'string' || !project[key]) throw new Error(`Project requires ${key}.`);
    return project;
}

function loadProject(root) { return validateProject(readJson(configFile(root, PROJECT_FILE))); }

function engineRootFor(root, project = {}, override) {
    const candidates = override ? [path.resolve(root, override)] : [
        path.join(root, 'node_modules', 'gameforgejs'),
        ...(project.enginePath ? [path.resolve(root, project.enginePath)] : []),
        ENGINE_ROOT,
    ];
    const found = candidates.find(candidate => fs.existsSync(path.join(candidate, 'src', 'core', 'index.js')));
    if (!found) throw new Error('GameForgeJS runtime was not found. Install the local npm pack archive, or provide --engine <package-directory>.');
    return fs.realpathSync(found);
}

function modulesSource(names) {
    if (names.some(name => !Object.hasOwn(MODULES, name))) throw new Error('Unknown official module.');
    const imports = names.map(name => `import { ${MODULES[name][1]} } from '${MODULES[name][0]}';`);
    return `// Generated by gameforge add. Keep custom modules in separate files.\n${imports.join('\n')}\n\nexport const createModules = () => [${names.map(name => `${MODULES[name][1]}()`).join(', ')}];\n`;
}

function version() { return readJson(path.join(ENGINE_ROOT, 'package.json')).version; }

function createProject(target, options = {}) {
    const root = path.resolve(target);
    assertNoLinks(root);
    if (fs.existsSync(root) && fs.readdirSync(root).length) throw new Error(`Project directory must be empty: ${root}`);
    const template = options.template || 'minimal-2d';
    if (!['minimal-2d', 'minimal-3d'].includes(template)) throw new Error('Choose --template minimal-2d or minimal-3d.');
    const name = options.name || path.basename(root);
    if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]*$/.test(name)) throw new Error('Project name may contain letters, numbers, dots, underscores and hyphens.');
    const engine = engineRootFor(process.cwd(), {}, options.engine);
    const relativeEngine = slash(path.relative(root, engine)) || '.';
    const modules = [template === 'minimal-3d' ? '3d' : '2d'];
    const project = { schemaVersion: 1, name, template, entry: 'index.html', runtimeConfig: 'config/game.config.json', resources: 'config/resources.json', modules, enginePath: relativeEngine, toolingVersion: version() };
    const templateRoot = path.join(ENGINE_ROOT, 'cli', 'templates', template);
    const writes = walk(templateRoot).filter(file => file.relative !== 'src/modules.js').map(file => ({ path: file.relative, content: fs.readFileSync(file.source, 'utf8').replaceAll('__PROJECT_NAME__', name) }));
    writes.push({ path: `config/${PROJECT_FILE}`, content: json(project) });
    writes.push({ path: 'src/modules.js', content: modulesSource(modules) });
    writes.push({ path: 'package.json', content: json({ name: name.toLowerCase(), version: '0.1.0', private: true, type: 'module', scripts: { dev: 'gameforge serve', build: 'gameforge build', doctor: 'gameforge doctor' }, dependencies: { gameforgejs: `file:${relativeEngine}` } }) });
    writes.push({ path: '.gitignore', content: 'node_modules/\ndist/\n' });
    return { root, ...applyWrites(root, writes, options) };
}

function addModule(root, name, options = {}) {
    if (!Object.hasOwn(MODULES, name)) throw new Error(`Unknown official module '${name}'. Available: ${Object.keys(MODULES).join(', ')}.`);
    const project = loadProject(root);
    if (project.modules.includes(name)) return { files: [], dryRun: !!options.dryRun };
    const next = validateProject({ ...project, modules: [...project.modules, name] });
    const writes = [
        { path: slash(path.relative(root, configFile(root, PROJECT_FILE))), previous: fs.readFileSync(configFile(root, PROJECT_FILE), 'utf8'), content: json(next) },
        { path: 'src/modules.js', previous: modulesSource(project.modules), content: modulesSource(next.modules) },
    ];
    const distribution = loadPackage(root);
    const group = name === 'audio' ? 'core' : name;
    if (distribution && !distribution.modules.includes(group)) writes.push({
        path: slash(path.relative(root, configFile(root, PACKAGE_FILE))), previous: fs.readFileSync(configFile(root, PACKAGE_FILE), 'utf8'),
        content: json({ ...distribution, modules: [...distribution.modules, group] }),
    });
    return applyWrites(root, writes, options);
}

function generate(root, kind, name, options = {}) {
    const project = loadProject(root);
    const directories = { level: 'levels', screen: 'screens', entity: 'entities', module: 'modules' };
    if (!directories[kind]) throw new Error('Generator must be level, screen, entity or module.');
    if (!/^[A-Z_a-z][\w]*$/.test(name || '')) throw new Error('Generated name must be a JavaScript identifier.');
    const is3d = project.template === 'minimal-3d';
    let content;
    if (kind === 'module') {
        content = `export function ${name}() {\n    return {\n        id: '${name}',\n        setup(context) {\n            const update = dt => { /* Update this module using dt in seconds. */ };\n            context.events.on('update', update);\n            return () => context.events.off('update', update);\n        },\n    };\n}\n`;
    } else if (kind === 'entity' && is3d) {
        content = `import { Base } from 'gameforgejs/core';\nimport { Mesh, PrimitiveMesh, UnlitMaterial } from 'gameforgejs/3d';\n\nexport class ${name} extends Base {\n    constructor() {\n        super();\n        this.mesh = new Mesh({\n            geometry: PrimitiveMesh.Cube(1),\n            material: new UnlitMaterial({ color: '#70baff' }),\n        });\n    }\n\n    OnUpdate(dt) {\n        this.mesh.transform.rotation.y += dt;\n    }\n}\n`;
    } else if (kind === 'entity') {
        content = `import { Vector2D } from 'gameforgejs/core';\nimport { Draw, GameObject } from 'gameforgejs/2d';\n\nexport class ${name} extends GameObject {\n    constructor(screen) {\n        super();\n        this.name = '${name}';\n        this.position = new Vector2D(100, 100);\n        this.size = new Vector2D(32, 32);\n        this.draw = new Draw(screen);\n    }\n\n    OnUpdate(dt) {\n        super.OnUpdate(dt);\n    }\n\n    OnDrawn() {\n        super.OnDrawn();\n        this.draw.Color = '#70baff';\n        this.draw.DrawRect(this.position.x, this.position.y, this.size.x, this.size.y);\n    }\n}\n`;
    } else if (is3d) {
        content = `import { Level3D, Mesh, PrimitiveMesh, UnlitMaterial } from 'gameforgejs/3d';\n\nexport class ${name} extends Level3D {\n    constructor() {\n        super({ useUI: false, usePhysics: false });\n        this.TelaId = '${name}';\n        this.caption = '${name}';\n    }\n\n    BuildScene() {\n        this.cube = new Mesh({\n            geometry: PrimitiveMesh.Cube(1.6),\n            material: new UnlitMaterial({ color: '#70baff' }),\n        });\n        this.scene.Add(this.cube);\n    }\n\n    OnUpdate(dt) {\n        super.OnUpdate(dt);\n        this.cube.transform.rotation.y += dt * 0.8;\n    }\n}\n`;
    } else {
        content = `import { Level } from 'gameforgejs/core';\nimport { Draw, Screen } from 'gameforgejs/2d';\n\nexport class ${name} extends Level {\n    constructor() {\n        super();\n        this.TelaId = '${name}';\n        this.caption = '${name}';\n    }\n\n    OnStart(context = this.context) {\n        const { width = 800, height = 450 } = context.config.screen ?? {};\n        this.screen = new Screen(this.TelaId, width, height, { config: context.config });\n        this.draw = new Draw(this.screen);\n        super.OnStart(context);\n    }\n\n    OnUpdate(dt) {\n        super.OnUpdate(dt);\n    }\n\n    OnGUI() {\n        super.OnGUI();\n    }\n}\n`;
    }
    return applyWrites(root, [{ path: `src/${directories[kind]}/${name}.js`, content }], options);
}

function update(root, options = {}) {
    const projectPath = configFile(root, PROJECT_FILE);
    const previous = fs.readFileSync(projectPath, 'utf8');
    const project = JSON.parse(previous);
    if (options.to && String(options.to) !== '1') throw new Error('Only project schema migration --to 1 is available offline.');
    if (project.schemaVersion !== 0 && project.schemaVersion !== 1) throw new Error(`No migration from schema ${project.schemaVersion}.`);
    // Version zero was the documented prototype manifest. Preserve all unknown
    // user keys and perform only the explicit defaults migration.
    const next = validateProject({ ...project, schemaVersion: 1, entry: project.entry || 'index.html', runtimeConfig: project.runtimeConfig || 'game.config.json', resources: project.resources || 'resources.json', modules: project.modules || [], toolingVersion: version() });
    const writes = [{ path: slash(path.relative(root, projectPath)), previous, content: json(next) }];
    const moduleFile = path.join(root, 'src/modules.js');
    if (!fs.existsSync(moduleFile)) writes.push({ path: 'src/modules.js', content: modulesSource(next.modules) });
    else if (fs.readFileSync(moduleFile, 'utf8') !== modulesSource(next.modules)) throw new Error('Conflict: src/modules.js differs from the generated module registry. Move custom modules to separate files before updating.');
    return applyWrites(root, writes, options);
}

function doctor(root, options = {}) {
    loadPackage(root);
    const project = loadProject(root);
    const engine = engineRootFor(root, project, options.engine);
    const problems = [];
    const { resolveInside } = require('./files.cjs');
    for (const file of [project.entry, project.runtimeConfig, project.resources, ...(project.template ? ['src/modules.js'] : [])]) {
        const target = resolveInside(root, file);
        if (!fs.existsSync(target)) problems.push(`Missing ${file}`);
    }
    if (fs.existsSync(path.join(root, project.runtimeConfig))) {
        const config = readJson(path.join(root, project.runtimeConfig));
        if (config.schemaVersion !== 1) problems.push('game.config.json requires schemaVersion: 1');
    }
    if (problems.length) throw new Error(`Project check failed:\n- ${problems.join('\n- ')}`);
    return { project: project.name, engine, schemaVersion: 1, modules: project.modules };
}

module.exports = { ENGINE_ROOT, PROJECT_FILE, MODULES, validateProject, loadProject, engineRootFor, modulesSource, createProject, addModule, generate, update, doctor };
